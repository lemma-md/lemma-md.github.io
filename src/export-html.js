// Export a note as a standalone .html file, and read one back.
//
// The file renders the note — Markdown and TeX — on its own in any browser: the
// libraries come from a CDN (pinned to the same versions this app vendors, so
// the output is identical), the original Markdown is embedded verbatim, and a
// small inline script renders it. There is no editor, menu or toolbar.
//
// The Markdown is HTML-escaped inside a `<script type="text/markdown">` block:
// escaping means the content can never contain `</script>` to break out, and it
// round-trips byte-for-byte, so dragging the file back in restores the source
// exactly rather than reverse-engineering it from rendered HTML.
//
// Two switches — see docs/HTML_EXPORT.md:
//   css: 'cdn'    github-markdown-css, or 'inline' — a self-contained stylesheet
//   js:  'min'    the pre-minified renderer, or 'full' — the readable copy
const OPTIONS = {
  css: 'cdn',
  js: 'min',
}

const CDN = 'https://cdn.jsdelivr.net/npm'
const MARKED_URL = `${CDN}/marked@18.0.9/lib/marked.umd.min.js`
const PURIFY_URL = `${CDN}/dompurify@3.4.13/dist/purify.min.js`
const KATEX_JS = `${CDN}/katex@0.18.2/dist/katex.min.js`
const KATEX_CSS = `${CDN}/katex@0.18.2/dist/katex.min.css`
// GitHub's own Markdown stylesheet (light + dark) for the `css: 'cdn'` option;
// it styles the `.markdown-body` container.
const GH_MD_CSS = `${CDN}/github-markdown-css@5/github-markdown.min.css`

function escapeHtml(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) => (
    { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]
  ))
}

function unescapeHtml(s) {
  return String(s ?? '')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, '&')
}

// The renderer that runs inside the exported file. It is written as a real
// function and serialised with `.toString()` so its regexes need no
// string-escaping and stay a faithful copy of src/viewer.js. It runs in the
// exported page against the CDN globals (marked, DOMPurify, katex); if those did
// not load — offline, or a blocked CDN — it falls back to showing the source as
// plain text. It must reference nothing from this module.
//
// The `js: 'min'` option ships RENDER_MIN below instead; regenerate that from
// this source with `python _tools/minify_render.py` after any edit here.
// >>> render-source >>>
function exportedRender() {
  var out = document.getElementById('content')
  var src = document.getElementById('md-source')
  var md = src
    ? src.textContent
        .replace(/&lt;/g, '<')
        .replace(/&gt;/g, '>')
        .replace(/&quot;/g, '"')
        .replace(/&#39;/g, "'")
        .replace(/&amp;/g, '&')
    : ''

  if (typeof marked === 'undefined' || typeof DOMPurify === 'undefined') {
    out.textContent = md
    return
  }

  var KATEX_OPTS = { throwOnError: false, errorColor: '#b00020', strict: false }
  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]
    })
  }
  function renderMath(tex, display) {
    try {
      return katex.renderToString(tex, Object.assign({}, KATEX_OPTS, { displayMode: display }))
    } catch (e) {
      return '<span class="katex-error">' + esc(e && e.message) + '</span>'
    }
  }

  marked.use({ gfm: true, breaks: false }, {
    extensions: [
      {
        name: 'mathBlock',
        level: 'block',
        start: function (s) { return s.indexOf('$$') },
        tokenizer: function (s) {
          var m = /^\$\$([\s\S]+?)\$\$(?:\n+|$)/.exec(s)
          if (m) return { type: 'mathBlock', raw: m[0], text: m[1].trim() }
        },
        renderer: function (t) { return renderMath(t.text, true) },
      },
      {
        name: 'mathInline',
        level: 'inline',
        start: function (s) { var i = s.indexOf('$'); return i < 0 ? undefined : i },
        tokenizer: function (s) {
          var m = /^\$(?![\s\d])([\s\S]*?[^\s\\])\$(?!\d)/.exec(s)
          if (m) return { type: 'mathInline', raw: m[0], text: m[1] }
        },
        renderer: function (t) { return renderMath(t.text, false) },
      },
    ],
  })

  DOMPurify.addHook('afterSanitizeAttributes', function (n) {
    if (n.tagName !== 'A') return
    var h = n.getAttribute('href') || ''
    if (!/^https?:/i.test(h)) return
    n.setAttribute('target', '_blank')
    n.setAttribute('rel', 'noopener noreferrer')
  })

  out.innerHTML = DOMPurify.sanitize(marked.parse(md), {
    USE_PROFILES: { html: true, mathMl: true, svg: true },
  })
}
// <<< render-source <<<

