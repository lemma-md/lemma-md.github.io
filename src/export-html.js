/** A self-contained HTML document that renders `markdown` on its own. */
export function buildStandaloneHtml(name, markdown) {
  const title = escapeHtml((name || '').replace(/\.md$/i, '') || 'note')
  const source = escapeHtml(markdown ?? '')
  const render = OPTIONS.js === 'min' && RENDER_MIN
    ? RENDER_MIN
    : `(${exportedRender.toString()})()`
  const head = OPTIONS.css === 'cdn'
    ? `<link rel="stylesheet" href="${GH_MD_CSS}">\n<style>${WRAPPER_CSS}</style>`
    : `<style>${INLINE_CSS}</style>`
  const cssClass = OPTIONS.css === 'cdn' ? ' class="markdown-body"' : ''

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${title}</title>
<script src="${MARKED_URL}"></script>
<script src="${PURIFY_URL}"></script>
<script src="${KATEX_JS}"></script>
<link rel="stylesheet" href="${KATEX_CSS}">
${head}
</head>
<body>
<article id="content"${cssClass}>Rendering…</article>
<script type="text/markdown" id="md-source">${source}</script>
<script>${render}</script>
</body>
</html>
`
}

/**
 * If `html` is a file this app exported, pull the note's Markdown back out of
 * it. Any other HTML returns null, so the caller can fall back to treating it as
 * plain text. The note's name is the caller's job — it comes from the filename.
 */
export function extractMarkdown(html) {
  try {
    const dom = new DOMParser().parseFromString(html, 'text/html')
    const el = dom.getElementById('md-source')
    return el ? unescapeHtml(el.textContent || '') : null
  } catch {
    return null
  }
}
